// installClaudeHarness installs the embedded Skills+Agents harness into the
// resolved Claude config dir and prints a per-file summary. The logic lives in
// core.InstallHarness; this handler only resolves the destination and renders.
func installClaudeHarness(cmd *cobra.Command, dryRun, force bool) error {
	claudeDir, err := resolveClaudeConfigDir()
	if err != nil {
		return err
	}

	res, err := core.InstallHarness(claude.FS, claudeDir, core.HarnessInstallOptions{DryRun: dryRun, Force: force})
	if err != nil {
		return fmt.Errorf("failed to install Claude harness: %w", err)
	}

	out := cmd.OutOrStdout()
	verb := "Installing"
	if dryRun {
		verb = "Would install"
	}
	fmt.Fprintf(out, "%s Claude harness into %s...\n", verb, claudeDir)
	for _, e := range res.Entries {
		note := ""
		if e.Action == core.HarnessSkipped {
			note = " (edited locally; pass --force to overwrite)"
		}
		// Show the path relative to the config dir for readability.
		rel, relErr := filepath.Rel(claudeDir, e.Dest)
		if relErr != nil {
			rel = e.Dest
		}
		fmt.Fprintf(out, "  %-9s %s%s\n", e.Action, filepath.ToSlash(rel), note)
	}
	fmt.Fprintf(out, "✓ Harness: %d installed, %d unchanged, %d skipped\n",
		res.Count(core.HarnessInstalled), res.Count(core.HarnessUnchanged), res.Count(core.HarnessSkipped))
	return nil
}

// resolveClaudeConfigDir returns the Claude Code config directory: $CLAUDE_CONFIG_DIR
// if set, else ~/.claude. This is the impure edge (env + home lookup); tests point
// CLAUDE_CONFIG_DIR at a temp dir to avoid touching the real config.
func resolveClaudeConfigDir() (string, error) {
	if d := os.Getenv("CLAUDE_CONFIG_DIR"); d != "" {
		return d, nil
	}
	home, err := os.UserHomeDir()
	if err != nil {
		return "", fmt.Errorf("resolving home directory for the Claude config dir: %w", err)
	}
	return filepath.Join(home, ".claude"), nil
}

// newSyncAllCmd creates the 'sync all' command
func newSyncAllCmd() *cobra.Command {
	cmd := &cobra.Command{
		Use:   "all",
		Short: "Regenerate all context files",
		Long: `Regenerate all context files (agent instructions, repo context, user context).

AGENTS.md is produced by the same multi-section generator 'sync context' uses,
so 'sync all' can never flatten the rich instruction file into the legacy backlog dump.`,
		RunE: func(cmd *cobra.Command, args []string) error {
			if App == nil {
				return fmt.Errorf("app not initialized")
			}
			if App.AIContextGenerator == nil {
				return fmt.Errorf("AI context generator not initialized")
			}

			// Create context generator
			contextGen := core.NewContextGenerator(
				App.BasePath+"/backlog.yaml",
				App.BasePath+"/tickets",
				App.BasePath,
				App.TemplateManager,
			)

			fmt.Println("Regenerating all context files...")

			// Deliberately NOT contextGen.GenerateAll(): its GenerateContext step is
			// the legacy backlog dump, which would undo the rich instruction file
			// that 'sync context' writes by default. Generate the three artifacts
			// individually so AGENTS.md comes from the multi-section generator — and
			// honour the same configured pointer set, or 'sync all' would quietly
			// write a different set of files than 'sync context'.
			results, err := App.AIContextGenerator.GenerateInto(
				configuredInstructionPointers(), false,
			)
			if err != nil {
				return fmt.Errorf("failed to regenerate agent instructions: %w", err)
			}
			reportInstructionResults(cmd, results)
			if err := contextGen.GenerateRepoContext(); err != nil {
				return fmt.Errorf("failed to generate repo context: %w", err)
			}
			if err := contextGen.GenerateClaudeUserContext(false, false); err != nil {
				return fmt.Errorf("failed to generate Claude user context: %w", err)
			}

			fmt.Println("✓ All context files regenerated")
			return nil
		},
	}

	return cmd
}

// taskIsKnown reports whether adb has any record of taskID — a backlog entry or
// a ticket directory on disk. It is the guard that stops `adb context task`
// from fabricating a ticket tree for a mistyped id and reporting success.
//
// Resolution goes through core.ResolveTicketDir rather than a bare path join, so
// a ticket nested under the correlation layout (tickets/<platform>/<org>/<repo>/…)
// counts as known — a flat-path-only check would reject every repo-backed ticket.
func taskIsKnown(taskID string) bool {
	if taskID == "" || App == nil {
		return false
	}
	if App.BacklogManager != nil {
		if task, err := App.BacklogManager.GetTask(taskID); err == nil && task != nil {
			return true
		}
	}
	dir, err := core.ResolveTicketDir(filepath.Join(App.BasePath, "tickets"), taskID)
	if err == nil && dir != "" {
		if info, statErr := os.Stat(dir); statErr == nil && info.IsDir() {
			return true
		}
	}
	return false
}
